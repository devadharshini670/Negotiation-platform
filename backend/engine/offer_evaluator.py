from llm.schema import AgentDecision

def validate(agent, decision):
    action=str(decision.action).lower(); value=decision.value; corrected=False; note=None
    if action not in {'open','accept','counter','reject','message'}:
        action='counter'; corrected=True; note='Unknown action converted to a safe counteroffer.'
    if action == 'message':
        return AgentDecision('message',None,decision.rationale or 'Message sent by the human participant.',decision.confidence,decision.source,decision.raw),False,None
    if action == 'message':
        return AgentDecision('message',None,decision.rationale or 'Message sent by the human participant.',decision.confidence,decision.source,decision.raw),False,None
    if action in {'open','counter','accept'}:
        try: value=float(value)
        except Exception: value=None
        if value is None:
            action='reject'; corrected=True; note='Missing numeric proposal; safe rejection applied.'
        elif action in {'open','counter'} and not agent.satisfies_limit(value):
            value=agent.clamp(value); corrected=True; note=f'Proposal clamped to the hard constraint {agent.limit}.'
    if action=='accept' and value is None: action='reject'; corrected=True
    return AgentDecision(action,value,decision.rationale or 'Decision generated by the negotiation engine.',decision.confidence,decision.source,decision.raw),corrected,note

def classify(agent,value):
    if value is None:return 'unknown'
    if not agent.satisfies_limit(value):return 'unacceptable'
    d=abs(value-agent.target)/agent.range_span()
    return 'strongly_favorable' if d<=.12 else 'favorable' if d<=.30 else 'negotiable' if d<=.60 else 'weak'
