"""Counteroffer evaluation and decision validation.

The Orchestrator is authoritative: whatever an agent (LLM or rule engine)
proposes is checked here against the agent's hard limit, its own previous
offer and the opponent's latest offer before it can change negotiation state."""
from llm.schema import AgentDecision
import math


class InvalidDecision(ValueError):
    """The agent output cannot be turned into a legal move (e.g. missing amount)."""


VALID_ACTIONS = {'open', 'accept', 'counter', 'reject', 'message'}


def _number(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None


def _dec(action, value, decision, note_rationale=None):
    return AgentDecision(action, value, note_rationale or decision.rationale or 'Decision generated by the negotiation engine.',
                         decision.confidence, decision.source, decision.raw)


def validate(agent, decision, opponent_last=None, own_last=None, allow_message=False, strict=False):
    """Return ``(decision, corrected, note)`` or raise :class:`InvalidDecision`.

    opponent_last / own_last are the numeric values of the latest public offers.
    With ``strict=True`` (human participants) violations raise a descriptive
    error instead of being silently corrected, and no step cap is applied."""
    action = str(decision.action).strip().lower()
    corrected, note = False, None

    if action not in VALID_ACTIONS:
        raise InvalidDecision(f'Unknown action "{decision.action}".')
    if action == 'message':
        if not allow_message:
            raise InvalidDecision('Agents may not send message-only turns.')
        return _dec('message', None, decision, decision.rationale or 'Message sent by the human participant.'), False, None
    if action == 'reject':
        return _dec('reject', None, decision), False, None

    if action == 'accept':
        if opponent_last is None:
            raise InvalidDecision('Nothing to accept: the opponent has not made an offer.')
        if not agent.satisfies_limit(opponent_last):
            if strict:
                raise InvalidDecision(f'You cannot accept {opponent_last:,.2f}: it violates your hard limit of {agent.limit:,.2f}. Counter or reject instead.')
            # Impossible acceptance -> safely turned into a counteroffer that holds the current position.
            held = own_last if own_last is not None else agent.opening
            return _dec('counter', agent.clamp(held), decision), True, \
                f'Acceptance blocked: the offer violates the hard limit ({agent.limit:g}); converted to a counteroffer.'
        value = _number(decision.value)
        if value is None or abs(value - opponent_last) > 1e-9:
            corrected, note = True, 'Accepted value was aligned to the opponent\'s actual latest offer.'
        return _dec('accept', opponent_last, decision), corrected, note

    # open / counter ---------------------------------------------------
    value = _number(decision.value)
    if value is None:
        raise InvalidDecision('Missing or non-numeric proposal.')
    if value <= 0:
        raise InvalidDecision('Proposal must be a positive amount.')
    if not agent.satisfies_limit(value):
        if strict:
            raise InvalidDecision(f'{value:,.2f} violates your hard limit of {agent.limit:,.2f}. Choose a value within your constraint.')
        value = agent.clamp(value)
        corrected, note = True, f'Proposal clamped to the hard constraint {agent.limit:g}.'
    if own_last is not None:
        # Never move backwards from an earlier position, and never concede more than the personality allows.
        step = agent.conceded_amount(own_last, value)
        if step < -1e-9 and strict:
            raise InvalidDecision(f'You cannot move backwards: your previous offer was {own_last:,.2f}. Hold or concede instead.')
        if step < -1e-9:
            value, corrected, note = own_last, True, 'Backward move blocked: an agent cannot retract a concession.'
        else:
            cap = agent.params()['max_step'] * agent.range_span()
            if step > cap + 1e-9 and not strict:
                direction = -1 if agent.direction.value == 'maximize' else 1
                value, corrected, note = round(own_last + direction * cap, 2), True, 'Concession capped to the personality\'s maximum single step.'
    if opponent_last is not None and agent.satisfies_limit(opponent_last):
        # A counter that is more generous than what the opponent already offers is pointless:
        # close the deal at the opponent's value instead.
        sign = 1 if agent.direction.value == 'maximize' else -1
        if (value - opponent_last) * sign < -1e-9:
            return _dec('accept', opponent_last, decision), True, 'Counter crossed the opponent\'s offer; converted to an acceptance of it.'
    action = 'counter' if own_last is not None or opponent_last is not None else 'open'
    return _dec(action, round(value, 2), decision), corrected, note


def classify(agent, value):
    """Where an offer sits between the agent's target (0) and its hard limit (1).

    Offers at or better than the target are strongly favourable to the agent;
    the closer an offer is to the hard limit, the more the agent has given up."""
    if value is None:
        return 'unknown'
    if not agent.satisfies_limit(value):
        return 'unacceptable'
    room = abs(agent.limit - agent.target) or 1e-9
    conceded = agent.conceded_amount(agent.target, value)     # > 0 once past the target toward the limit
    frac = conceded / room
    return 'strongly_favorable' if frac <= 0 else 'favorable' if frac <= .30 else 'negotiable' if frac <= .65 else 'weak'


# Live stance indicator: how firmly the *proposing* agent is holding its own
# ground on the offer it just made (distance from its own target/limit).
STANCE_LABELS = {'strongly_favorable': 'Firmly anchored', 'favorable': 'Holding ground', 'negotiable': 'Moving to the middle',
                 'weak': 'Near its limit', 'unacceptable': 'Off the table', 'unknown': None}


def stance_label(agent, value):
    return STANCE_LABELS.get(classify(agent, value))
